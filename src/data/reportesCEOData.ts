/**
 * Clave de persistencia para los contadores de impresión
 */
export const STORAGE_KEY_REPORTES_IMPRESIONES = 'sisceba_reportes_impresiones_v2';

/**
 * Obtiene el mapa actual de impresiones por reporte (con fallback a los valores por defecto de CEO)
 */
export function getReportesImpresionesMap(): Record<string, number> {
  try {
    const raw = localStorage.getItem(STORAGE_KEY_REPORTES_IMPRESIONES);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (typeof parsed === 'object' && parsed !== null) {
        return {
          ...Object.fromEntries(CATALOGO_REPORTES_CEO.map(r => [r.id, r.impresionesDefault])),
          ...parsed
        };
      }
    }
  } catch (e) {
    console.error('Error leyendo impresiones de reportes:', e);
  }
  return Object.fromEntries(CATALOGO_REPORTES_CEO.map(r => [r.id, r.impresionesDefault]));
}

/**
 * Incrementa en +1 el conteo de impresiones de un reporte y lo persiste
 */
export function incrementReporteImpresiones(reporteId: string): number {
  const currentMap = getReportesImpresionesMap();
  const nextCount = (currentMap[reporteId] ?? 0) + 1;
  currentMap[reporteId] = nextCount;
  try {
    localStorage.setItem(STORAGE_KEY_REPORTES_IMPRESIONES, JSON.stringify(currentMap));
  } catch (e) {
    console.error('Error guardando contador de impresiones:', e);
  }
  return nextCount;
}

/**
 * Resetea el contador de impresiones a los valores históricos de CEO
 */
export function resetReportesImpresiones(): Record<string, number> {
  const defaults = Object.fromEntries(CATALOGO_REPORTES_CEO.map(r => [r.id, r.impresionesDefault]));
  try {
    localStorage.setItem(STORAGE_KEY_REPORTES_IMPRESIONES, JSON.stringify(defaults));
  } catch (e) {
    console.error('Error reseteando impresiones:', e);
  }
  return defaults;
}

export const STORAGE_KEY_REPORTES_CONFIG = 'siscba_reportes_config_map_v1';

export interface ReporteConfigOverrides {
  nombre?: string;
  url?: string;
  orden?: number;
  visible?: 'SI' | 'NO';
  descripcion?: string;
  fondoCabecera?: string;
  letrasCabecera?: string;
  fondoFilaPar?: string;
  fondoFilaImpar?: string;
}

/**
 * Obtiene el mapa de configuraciones personalizadas de reportes guardadas en el navegador
 */
export function getReportesConfigMap(): Record<string, ReporteConfigOverrides> {
  try {
    const raw = localStorage.getItem(STORAGE_KEY_REPORTES_CONFIG);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (typeof parsed === 'object' && parsed !== null) {
        return parsed;
      }
    }
  } catch (e) {
    console.error('Error leyendo configuraciones de reportes:', e);
  }
  return {};
}

/**
 * Guarda o actualiza la configuración personalizada de un reporte
 */
export function saveReporteConfig(reporteId: string, overrides: ReporteConfigOverrides): Record<string, ReporteConfigOverrides> {
  const current = getReportesConfigMap();
  current[reporteId] = {
    ...(current[reporteId] || {}),
    ...overrides
  };
  try {
    localStorage.setItem(STORAGE_KEY_REPORTES_CONFIG, JSON.stringify(current));
  } catch (e) {
    console.error('Error guardando configuración de reporte:', e);
  }
  return current;
}

/**
 * Retorna el catálogo completo con las configuraciones personalizadas aplicadas
 */
export function getMergedReportesCatalog(): ReporteItem[] {
  const configs = getReportesConfigMap();
  return CATALOGO_REPORTES_CEO.map((item) => {
    const custom = configs[item.id];
    if (!custom) return item;
    return {
      ...item,
      ...custom,
      // Respetar visibilidad y orden si fueron modificados
      nombre: custom.nombre ?? item.nombre,
      url: custom.url ?? item.url,
      orden: custom.orden !== undefined ? custom.orden : item.orden,
      visible: custom.visible ?? item.visible,
      descripcion: custom.descripcion ?? item.descripcion,
      fondoCabecera: custom.fondoCabecera ?? item.fondoCabecera,
      letrasCabecera: custom.letrasCabecera ?? item.letrasCabecera,
      fondoFilaPar: custom.fondoFilaPar ?? item.fondoFilaPar,
      fondoFilaImpar: custom.fondoFilaImpar ?? item.fondoFilaImpar,
    };
  });
}

